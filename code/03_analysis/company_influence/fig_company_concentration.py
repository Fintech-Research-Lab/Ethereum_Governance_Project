"""
fig_company_concentration.py
==============================

Reproduces **Figure 20** (`\\label{fig:ncomp}`, "Organizations Affiliated with EIP Authors and
Client Developers", panels a-c) and **Figure 21** (`\\label{fig:ef_year}`, "Influence of Ethereum
Foundation over Time") of the current manuscript, `paper/latex/MS_R2.tex`. Panel (d) of
Figure 20 is produced by `code/03_analysis/client_concentration/fig_client_concentration.py`
instead (see that script's docstring). Figure numbers shift as the paper is revised; see
`docs/figure_table_index.md` for the current numbering snapshot and its date.

    Fracassi, C., Khoja, M., & Schar, F. (2024). "Decentralized Crypto Governance? Transparency
    and Concentration in Ethereum Decision-Making." SSRN 4691000.

Paper section: concentration of EIP authorship by employer/company, and the Ethereum Foundation's
share of EIP co-authorship over time.

Ported from: `Analysis\\Regression Code\\Regression Code.do`, the "ADD TOP10 COMPANY DUMMIES AND PLOT
EMPLOYMENT OF EIP AUTHORS" section and the "ETHEREUM TIME TRENDS" section's Ethereum-Foundation-share
block.

Output produced by this script (confirmed against the paper's own LaTeX `\includegraphics` list --
see `make_company_bar_charts`'s docstring for the one output the original code computed that is NOT
part of the published paper and is therefore no longer generated here at all):
    Figure 20a: company_lorenz.png -- Lorenz curve of company-level concentration by author count
    Figure 20b: company_neip2.png -- top-10 companies by count of distinct affiliated authors
    Figure 20c: company_neip3.png -- top-10 companies by count of distinct EIPs touched
    Figure 21:  eip_ef_by_year.png -- % of EIPs co-authored by an Ethereum-Foundation-affiliated author
                by year, split into All / ERC / Core subsets

Historical note: `cdum_coef.png` (a company-fixed-effect coefficient plot, produced by
`table3_finalization_regressions.py`) used to be cross-referenced here as a companion to this
script's figures. That script (and the EIP-finalization/implementation regression it supported) is
no longer part of the published paper and has been moved to `archive/code/` -- see
`archive/README.md`. `cdum_coef.png` is not generated by this package's active pipeline.

Data source
-----------
`DATA_PROCESSED / "ethereum_cross_sectional_data.parquet"` (see
`table3_finalization_regressions.py`'s docstring for the full expected column list). This script needs
the wide `author{n}` / `author{n}_id` / `author{n}_company{c}` (n=1..15, c=1..5) and
`author{n}_EF_start` / `author{n}_EF_end` columns, plus `eip_number`, `Category` (capitalized --
confirmed against `code/02_data_preparation/build_cross_sectional_dataset.py`'s actual output
columns), `sdate`.

Note on duplicated logic
------------------------
The wide-to-long author/company reshape (`_build_author_company_long`) and the top-10-company
selection (`top10_companies`) are re-implemented independently in
`code/03_analysis/regressions/table3_finalization_regressions.py` (which needs the same panel to
build its `cdum_*` regressors). This is a deliberate duplication rather than a cross-folder import
(`03_analysis` is not a valid Python package/module name, which makes a clean dotted import across its
subfolders awkward) -- see that file's module docstring for the same note.
"""

from __future__ import annotations

import sys
from pathlib import Path

import matplotlib.pyplot as plt
import polars as pl

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))  # add code/ to sys.path

from config import DATA_PROCESSED, OUTPUT_FIGURES, ensure_dirs
from utils.inequality import gini, lorenz_curve

CROSS_SECTIONAL_PATH = DATA_PROCESSED / "ethereum_cross_sectional_data.parquet"
N_AUTHOR_SLOTS = 15
N_COMPANY_SLOTS = 5


def _build_author_company_long(df: pl.DataFrame) -> pl.DataFrame:
    """
    Reshape the wide author{n}_company{c} slot columns into a long (eip_number, author_id, company)
    panel, replicating:
        tostring author*_company*, replace
        reshape long author@_id author@_company1...5, i(eip_number) j(id) string
        drop if author_id==.
        duplicates drop
        reshape long author_company, i(eip_number author_id) j(c) string
        rename author_company company
        drop c
        duplicates drop

    Stata's `tostring` of a numeric-missing company slot produces the literal string "." (not "");
    here we simply keep true nulls as nulls and treat "" the same way downstream, which is
    functionally equivalent.
    """
    frames = []
    for a in range(1, N_AUTHOR_SLOTS + 1):
        id_col = f"author{a}_id"
        if id_col not in df.columns:
            continue
        for c in range(1, N_COMPANY_SLOTS + 1):
            comp_col = f"author{a}_company{c}"
            if comp_col not in df.columns:
                continue
            frames.append(
                df.select(
                    pl.col("eip_number"),
                    pl.col(id_col).alias("author_id"),
                    pl.col(comp_col).cast(pl.Utf8).alias("company"),
                )
            )
    if not frames:
        raise KeyError("No author{n}_id / author{n}_company{c} columns found in df.")
    long_df = pl.concat(frames, how="vertical")
    long_df = long_df.filter(pl.col("author_id").is_not_null())
    return long_df.unique()


def _non_missing_company(long_df: pl.DataFrame) -> pl.DataFrame:
    return long_df.filter((pl.col("company").is_not_null()) & (pl.col("company") != "") & (pl.col("company") != "."))


def top10_companies(long_df: pl.DataFrame) -> list[str]:
    """Top-10 companies by count of (author, eip) affiliation pairs, replicating `gsort -one company`
    then `if _n<11`."""
    counts = (
        _non_missing_company(long_df)
        .group_by("company")
        .agg(pl.len().alias("one"))
        .sort(["one", "company"], descending=[True, False])
    )
    return counts.head(10).get_column("company").to_list()


def _hbar_top10(counts: pl.DataFrame, label_col: str, value_col: str, ylabel: str, out_path: Path) -> None:
    # Break ties deterministically by label (ascending), via a stable sort on the count -- several
    # companies are tied at the same count (there are 8 tied at 3 for the "by author" chart alone),
    # so without this, which ones land in the top 10 (not just their display order) depends on
    # `counts`'s own row order, which Polars' group_by does not guarantee is stable across runs.
    top10 = counts.sort(label_col).sort(value_col, descending=True, maintain_order=True).head(10)
    labels = top10.get_column(label_col).to_list()
    values = top10.get_column(value_col).to_list()
    fig, ax = plt.subplots(figsize=(7, max(2.5, 0.4 * len(labels))))
    ax.barh(range(len(labels)), values)
    ax.set_yticks(range(len(labels)))
    ax.set_yticklabels(labels)
    ax.invert_yaxis()
    ax.set_xlabel(ylabel)
    fig.tight_layout()
    fig.savefig(out_path, dpi=200)
    plt.close(fig)


def make_company_bar_charts(long_df: pl.DataFrame) -> None:
    """
    company_neip2.png (Figure 20b), company_neip3.png (Figure 20c).

    The original `Regression Code.do` also builds a THIRD bar chart, `company_neip1.png` (top-10
    companies by raw count of (author, EIP) affiliation *pairs*, i.e. not deduplicated by author or
    by EIP). Confirmed directly against the paper's own LaTeX source
    (`paper/Decentralized_Crypto_Governance_LaTeX_source.zip`, `\includegraphics` list for Figure
    16): only `company_lorenz.png` (a), `company_neip2.png` (b), `company_neip3.png` (c), and
    `client_company.png` (d) are ever shown to readers -- `company_neip1.png` is not part of the
    published paper and is not computed here.
    """
    non_missing = _non_missing_company(long_df)

    authors = non_missing.select(["author_id", "company"]).unique().group_by("company").agg(
        pl.len().alias("n")
    )
    _hbar_top10(authors, "company", "n", "N. Authors", OUTPUT_FIGURES / "company_neip2.png")

    eips = non_missing.select(["eip_number", "company"]).unique().group_by("company").agg(pl.len().alias("n"))
    _hbar_top10(eips, "company", "n", "N. EIP", OUTPUT_FIGURES / "company_neip3.png")


def make_company_lorenz(long_df: pl.DataFrame) -> None:
    """
    company_lorenz.png -- Lorenz curves of company-level concentration by (a) distinct-author count
    and (b) distinct-EIP count. The original also computes (and merges in, via temp_lor1) a third
    "author-EIP pair count" Lorenz series, but never actually plots it (only cum_n_one2/cum_n_one3
    appear in the final `twoway line` call) -- that unused series is not reproduced here.
    """
    non_missing = _non_missing_company(long_df)

    authors_per_company = (
        non_missing.select(["author_id", "company"]).unique().group_by("company").agg(pl.len().alias("n"))
    )
    eips_per_company = (
        non_missing.select(["eip_number", "company"]).unique().group_by("company").agg(pl.len().alias("n"))
    )

    lc_authors = lorenz_curve(authors_per_company.get_column("n"), descending=True)
    lc_eips = lorenz_curve(eips_per_company.get_column("n"), descending=True)

    gini_authors = gini(authors_per_company.get_column("n"))
    gini_eips = gini(eips_per_company.get_column("n"))
    print(
        f"[fig_company_concentration] Company-concentration Gini -- "
        f"by author count: {gini_authors:.4f}, by EIP count: {gini_eips:.4f}"
    )

    fig, ax = plt.subplots(figsize=(7, 6))
    ax.plot(lc_authors["pct_population"], lc_authors["cum_pct_value"], label="% Authors")
    ax.plot(lc_eips["pct_population"], lc_eips["cum_pct_value"], label="% EIPs")
    ax.set_xlabel("% of Companies")
    ax.set_ylabel("% of EIPs / Authors")
    ax.legend(loc="lower right")
    fig.tight_layout()
    fig.savefig(OUTPUT_FIGURES / "company_lorenz.png", dpi=200)
    plt.close(fig)


def add_ef_dummy(df: pl.DataFrame) -> pl.DataFrame:
    """
    Replicates `compdum_EF2`: 1 if any author-slot's Ethereum Foundation affiliation window
    (`author{n}_EF_start` .. `author{n}_EF_end`, end possibly missing/open-ended) covers the EIP's
    start year. The original's inner `forvalues c = 1/5` loop over company slots is redundant dead
    code (EF_start/EF_end do not vary by company slot) and is not reproduced.
    """
    year = pl.col("sdate").dt.year()
    conditions = []
    for a in range(1, N_AUTHOR_SLOTS + 1):
        start_col, end_col = f"author{a}_EF_start", f"author{a}_EF_end"
        if start_col not in df.columns or end_col not in df.columns:
            continue
        conditions.append(
            pl.col(start_col).is_not_null()
            & (pl.col(start_col) <= year)
            & (pl.col(end_col).is_null() | (pl.col(end_col) >= year))
        )
    if not conditions:
        raise KeyError("No author{n}_EF_start/EF_end columns found in df.")
    is_ef = pl.any_horizontal(conditions)
    return df.with_columns(pl.when(is_ef).then(1).otherwise(0).alias("compdum_EF2"))


def make_eip_ef_by_year(df: pl.DataFrame) -> None:
    """
    eip_ef_by_year.png -- % of EIPs (co-)authored by an Ethereum-Foundation-affiliated author, by
    year, for All EIPs / ERC (+Interface) EIPs / Core (+Networking) EIPs, replicating the
    `forvalues y = 2015/2023 { ... }` block.
    """
    df = add_ef_dummy(df).with_columns(pl.col("sdate").dt.year().alias("year"))
    df = df.filter((pl.col("year") >= 2015) & (pl.col("year") <= 2023))

    is_erc = pl.col("Category").is_in(["ERC", "Interface"])
    is_core = pl.col("Category").is_in(["Core", "Networking"])

    by_year = df.group_by("year").agg(
        pl.len().alias("tot"),
        (pl.col("compdum_EF2") == 1).sum().alias("EF"),
        is_erc.sum().alias("tot_erc"),
        ((pl.col("compdum_EF2") == 1) & is_erc).sum().alias("EF_erc"),
        is_core.sum().alias("tot_core"),
        ((pl.col("compdum_EF2") == 1) & is_core).sum().alias("EF_core"),
    ).with_columns(
        (pl.col("EF") / pl.col("tot")).alias("frac"),
        (pl.col("EF_erc") / pl.col("tot_erc")).alias("frac_erc"),
        (pl.col("EF_core") / pl.col("tot_core")).alias("frac_core"),
    ).sort("year")

    fig, ax = plt.subplots(figsize=(8, 5))
    ax.plot(by_year["year"], by_year["frac"], label="All EIPs", marker="o")
    ax.plot(by_year["year"], by_year["frac_erc"], label="ERCs EIPs", marker="o")
    ax.plot(by_year["year"], by_year["frac_core"], label="Core EIPs", marker="o")
    ax.set_xlabel("Year")
    ax.set_ylabel("% EIPs Co-Authored by Ethereum Foundation")
    ax.set_xticks(list(range(2015, 2024)))
    ax.legend()

    years_list = by_year.get_column("year").to_list()
    if 2023 in years_list:
        idx2023 = years_list.index(2023)
        top_2023 = max(
            by_year.get_column("frac").to_list()[idx2023],
            by_year.get_column("frac_erc").to_list()[idx2023],
            by_year.get_column("frac_core").to_list()[idx2023],
        )
        ax.text(
            2023,
            top_2023 + 0.03 * (ax.get_ylim()[1] - ax.get_ylim()[0]),
            "*",
            ha="center",
            va="bottom",
            fontsize=16,
            fontweight="bold",
        )

    fig.tight_layout()
    fig.savefig(OUTPUT_FIGURES / "eip_ef_by_year.png", dpi=200)
    plt.close(fig)


def main() -> None:
    ensure_dirs()

    df = pl.read_parquet(CROSS_SECTIONAL_PATH)

    long_df = _build_author_company_long(df)
    make_company_bar_charts(long_df)
    make_company_lorenz(long_df)
    make_eip_ef_by_year(df)


if __name__ == "__main__":
    main()
